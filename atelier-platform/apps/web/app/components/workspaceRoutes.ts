export function pageForPath(path: string) {
  if (path === "/form-submissions") return "Intake forms";
  if (/^\/customers\/[\da-f-]{36}$/i.test(path)) return "Customers";
  return (
    Object.keys(workspaceRoutes).find(
      (name) => workspaceRoutes[name] === path,
    ) || "Quick Work"
  );
}
